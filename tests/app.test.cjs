'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../src/index.html'),'utf8');
const app=fs.readFileSync(path.join(__dirname,'../src/app.js'),'utf8');
const dist=fs.readFileSync(path.join(__dirname,'../dist/html_dbms.html'),'utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert.equal(ids.length,new Set(ids).size);
for(const id of ['new-db','databases','head-id','head-hash','open-head','save','debug-toggle','entry-area','more-menu'])assert.ok(html.includes('id="'+id+'"'),id);
for(const forbidden of ['new-doc','edit','patch-input','view-table','documents'])assert.ok(!html.includes('id="'+forbidden+'"'),forbidden);
assert.match(app,/async function openFields\(\)\{await openHead\(fieldHead\(\)\);\}/);
assert.match(app,/srcdoc=SANDBOX_DOCUMENT/);
assert.match(app,/setAttribute\('sandbox','allow-scripts'\)/);
assert.ok(!app.includes('allow-same-origin'));
assert.match(app,/const exportTemplate=document\.documentElement\.cloneNode\(true\)/);
assert.match(app,/textContent=JSON\.stringify\(store\)/);
assert.ok(!dist.includes('/* CORE_JS */'));assert.ok(!dist.includes('/* APP_JS */'));assert.ok(!dist.includes('/* STARTER_JS */'));
console.log('HTML_DBMS/3 shell UI tests PASS');
