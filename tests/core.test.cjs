'use strict';
const assert=require('node:assert/strict'),db=require('../src/core.js');
(async()=>{
 const s=db.newStore();assert.equal(s.format,'HTML_DBMS/3');
 const root=await db.createDatabase(s,'Касса',{visible:true,entry:{type:'text/plain',value:'ok'}});
 db.commit(s,root.store);assert.deepEqual(s.publicHeads['Касса'],root.rootHead);
 const genesis=await db.readRecord(s,root.rootHead);
 assert.deepEqual(genesis[0],null);assert.equal(genesis.length,2);
 const child=await db.createDocument(s,root.rootHead,'funds',{F001:{name:'A'}});
 db.commit(s,child.store);
 assert.deepEqual((await db.load(s,child.documentHead)).genesis.parent,root.rootHead);
 const r=await db.readRecord(s,child.rootHead);assert.equal(r.length,4);
 assert.equal(r[1],root.rootHead[0]);assert.equal(r[2],root.rootHead[1]);
 assert.ok(/^\\d{4}-/.test(r[0]));assert.equal(r[3].length,1);
 assert.equal((await db.resolve(s,child.rootHead,child.rootHead,{$ref:'funds/F001/name'})).value,'A');
 const upd=await db.patchDocument(s,child.rootHead,'funds',[{op:'replace',path:'/F001/name',value:'B'}]);
 db.commit(s,upd.store);
 assert.equal((await db.resolve(s,upd.rootHead,upd.rootHead,{$ref:'funds/F001/name'})).value,'B');
 assert.equal((await db.resolve(s,child.rootHead,child.rootHead,{$ref:'funds/F001/name'})).value,'A');
 assert.equal((await db.load(s,upd.rootHead)).events.length,3);
 assert.deepEqual(s.publicHeads['Касса'],root.rootHead);
 const tx=db.staging(s);db.publish(tx,'Касса',upd.rootHead,root.rootHead);db.commit(s,tx);
 const w=await db.createDatabase(s,'Склад');db.commit(s,w.store);assert.equal(Object.keys(s.publicHeads).length,2);
 const hidden=await db.createDatabase(s,'Бухгалтерия',{visible:false});db.commit(s,hidden.store);
 assert.equal(s.publicHeads['Бухгалтерия'],undefined);
 const anonymous=db.staging(s);delete anonymous.publicHeads;db.validateStore(anonymous);
 assert.equal((await db.load(anonymous,hidden.rootHead)).state.name,'Бухгалтерия');
 assert.throws(()=>db.validateStore({...s,format:'HTML_DBMS/2.2'}));
 await assert.rejects(db.append(s,child.rootHead,[{op:'add',path:'/x',value:1}]),{code:'SUCCESSOR_OCCUPIED'});
 await assert.rejects(db.append(s,upd.rootHead,[]),{code:'INVALID_PATCH'});
 assert.equal((await db.inspect(s,upd.rootHead)).status,'complete');
 console.log('HTML_DBMS/3 core tests PASS');
})().catch(e=>{console.error(e);process.exitCode=1;});
